    av = Image.open(bajar(c["avatar"], os.path.join(tmp, "avatar.jpg"))).convert("RGBA").resize((104, 104), Image.LANCZOS)
    m = Image.new("L", (416, 416), 0); ImageDraw.Draw(m).ellipse([0, 0, 415, 415], fill=255)
    av.putalpha(m.resize((104, 104), Image.LANCZOS))
    f = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 40)
    tw = int(ImageDraw.Draw(av).textlength(c["nombre"], font=f))
    im = Image.new("RGBA", (104 + 24 + tw + 34, 120), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
