async def _tts(texto, voz, mp3):
    import edge_tts
    try:
        com = edge_tts.Communicate(texto, voz, rate="+10%", boundary="WordBoundary")
    except TypeError:
        com = edge_tts.Communicate(texto, voz, rate="+10%")
    pal, sent = [], []
    with open(mp3, "wb") as f:
        async for ch in com.stream():
            if ch["type"] == "audio":
                f.write(ch["data"])
            elif ch["type"] in ("WordBoundary", "SentenceBoundary"):
                item = (ch["offset"] / 1e7, (ch["offset"] + ch["duration"]) / 1e7, ch["text"])
                (pal if ch["type"] == "WordBoundary" else sent).append(item)
    return pal, sent


def narrar(texto, voz, mp3, wav):
    """UNA sola locución para todo el guion (fluida, sin cortes entre escenas).
    Devuelve [(ini, fin, palabra_con_puntuación, pos_en_texto)] y la duración real (WAV, exacta)."""
    import time
    for intento in range(4):
        try:
            pal, sent = asyncio.run(_tts(texto, voz, mp3))
            if os.path.getsize(mp3) < 1000:
                raise RuntimeError("audio vacío")
            break
        except Exception as ex:
            if intento == 3:
                raise
            print("tts reintento", ex, file=sys.stderr); time.sleep(3 + intento * 3)
    ff("-i", mp3, "-ar", "48000", "-ac", "1", wav)
    d = dur(wav)
    if not pal and sent:  # solo hay límites de frase: se reparten las palabras dentro de cada frase por longitud
        for a, b, frase in sent:
            ws = frase.split(); tot = sum(len(w) + 1 for w in ws) or 1; t = a
            for w in ws:
                dt = (b - a) * (len(w) + 1) / tot; pal.append((t, t + dt, w)); t += dt
    if not pal:
        ws = texto.split(); step = d / max(1, len(ws))
        pal = [(i * step, (i + 1) * step, w) for i, w in enumerate(ws)]
    # alinear cada palabra con su posición en el texto original (recupera la puntuación para los subtítulos)
    out, cur = [], 0
    for a, b, w in pal:
        w = w.strip()
        if not w:
            continue
        p = texto.find(w, cur)
        if p < 0:
            p = cur
        fin = p + len(w)
        while fin < len(texto) and not texto[fin].isspace():
            fin += 1
        out.append((a, b, texto[p:fin] if p >= cur else w, p))
        cur = fin
    return out, d


