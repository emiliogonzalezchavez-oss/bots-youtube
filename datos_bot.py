# ---------- búsqueda de material real ----------
def es_real(h):
    if h.get("isAiGenerated") or h.get("isLowQuality"):
        return False
    t = h.get("tags", "").lower()
    return not any(p in t for p in PROHIBIDO)


def relevancia(h, clave):
    """Posición de la palabra clave en los tags (menor = más relevante). None si no aparece."""
    tags = [x.strip() for x in h.get("tags", "").lower().split(",")]
    palabras = clave.lower().split()
    for i, t in enumerate(tags):
        if all(p in t for p in palabras):
            return i
    return None


def pixabay_videos(q, clave, usados):
    url = "https://pixabay.com/api/videos/?" + urllib.parse.urlencode({"key": KEY, "q": q, "per_page": 50, "safesearch": "true"})
    out = []
    for h in get_json(url).get("hits", []):
        r = relevancia(h, clave)
        if h["id"] in usados or not es_real(h) or r is None or r > 4 or h.get("duration", 0) < 4:
            continue
        out.append((r, -h.get("likes", 0), h))
    out.sort(key=lambda x: x[:2])
    return [h for _, _, h in out]


def pixabay_imagenes(q, clave, usados):
    url = "https://pixabay.com/api/?" + urllib.parse.urlencode(
        {"key": KEY, "q": q, "per_page": 50, "safesearch": "true", "image_type": "photo"})
    out = []
    for h in get_json(url).get("hits", []):
        r = relevancia(h, clave)
        if h["id"] in usados or not es_real(h) or r is None or r > 4:
            continue
        out.append((r, h["imageWidth"] > h["imageHeight"], -h.get("likes", 0), h))
    out.sort(key=lambda x: x[:3])
    return [h for *_, h in out]


def commons(q, clave, usados):
    url = "https://commons.wikimedia.org/w/api.php?" + urllib.parse.urlencode({
        "action": "query", "format": "json", "generator": "search", "gsrnamespace": 6, "gsrsearch": q,
        "gsrlimit": 15, "prop": "imageinfo", "iiprop": "url|extmetadata|mime", "iiurlwidth": 1600})
    pages = get_json(url).get("query", {}).get("pages", {})
    out = []
    for p in sorted(pages.values(), key=lambda p: p.get("index", 99)):
        ii = (p.get("imageinfo") or [{}])[0]
        meta = ii.get("extmetadata", {})
        cats = meta.get("Categories", {}).get("value", "").lower()
        titulo = p.get("title", "").lower()
        if p["pageid"] in usados or "ai-generated" in cats or "ai generated" in cats:
            continue
        if not ii.get("mime", "").startswith("image/") or ii.get("mime") == "image/gif":
            continue
        if not all(w in (titulo + " " + cats) for w in clave.lower().split()):
            continue
        import html; autor = html.unescape(re.sub(r"<[^>]+>", "", meta.get("Artist", {}).get("value", ""))).strip()[:60]
        lic = meta.get("LicenseShortName", {}).get("value", "")
        out.append({"id": p["pageid"], "url": ii.get("thumburl") or ii["url"], "credito": f"{autor} ({lic}), Wikimedia Commons"})
    return out


# ---------- armado de clips ----------
def clip_video(src, seg, out, offset=0.15):
    d = dur(src); ini = max(0.0, min(d - seg - 0.1, d * offset))
    ff("-ss", f"{ini:.2f}", "-i", src, "-t", f"{seg:.3f}", "-an",
       "-vf", f"scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H},fps={FPS},setsar=1",
       "-c:v", "libx264", "-preset", "ultrafast", "-crf", "20", "-threads", "1", "-pix_fmt", "yuv420p", out)


def clip_imagen(src, seg, out, completo=False):
    """Foto con zoom lento. completo=True (diagramas): se ve entera sobre fondo desenfocado."""
    n = int(seg * FPS)
    if completo:
        vf = (f"split[a][b];[a]scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H},boxblur=30:5,eq=brightness=-0.15[bg];"
              f"[b]scale={W - 60}:{H - 700}:force_original_aspect_ratio=decrease,pad=iw+20:ih+20:10:10:white[fg];"
              f"[bg][fg]overlay=(W-w)/2:220,zoompan=z='min(zoom+0.0004,1.06)':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d={n}:s={W}x{H}:fps={FPS},setsar=1")
    else:
        z = random.choice(["min(zoom+0.0009,1.22)", "if(eq(on,0),1.22,max(zoom-0.0009,1))"])
        vf = (f"scale={W * 2}:{H * 2}:force_original_aspect_ratio=increase,crop={W * 2}:{H * 2},"
              f"zoompan=z='{z}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d={n}:s={W}x{H}:fps={FPS},setsar=1")
    ff("-loop", "1", "-i", src, "-t", f"{seg:.3f}", "-an", "-vf", vf,
       "-c:v", "libx264", "-preset", "ultrafast", "-crf", "20", "-threads", "1", "-pix_fmt", "yuv420p", out)


def material_escena(e, seg, tmp, idx, usados, creditos):
    """Devuelve lista de clips (mp4) que cubren 'seg' segundos, con material de esta escena."""
    q, clave = e["buscar"], e.get("clave") or e["buscar"].split()[0]
    fuente = e.get("fuente", "video")
    partes = 2 if seg > 7 else 1
    sub = seg / partes
    orden = {"video": ["video", "imagen", "diagrama"], "imagen": ["imagen", "video", "diagrama"],
             "diagrama": ["diagrama", "imagen", "video"]}[fuente]
    clips = []
    for tipo in orden:
        try:
            if tipo == "video":
                for h in pixabay_videos(q, clave, usados):
                    if len(clips) >= partes:
                        break
                    v = h["videos"]["medium"] if h["videos"]["medium"]["url"] else h["videos"]["small"]
                    src = bajar(v["url"], os.path.join(tmp, f"src{idx}_{len(clips)}.mp4"))
                    out = os.path.join(tmp, f"e{idx}_{len(clips)}.mp4")
                    try:
                        clip_video(src, sub, out)
                        clips.append(out); usados.add(h["id"]); creditos.add(f"{h['user']} (Pixabay)")
                    except Exception:
                        pass
                    finally:
                        os.remove(src)
            elif tipo == "imagen":
                for h in pixabay_imagenes(q, clave, usados)[:partes - len(clips)]:
                    src = bajar(h["largeImageURL"], os.path.join(tmp, f"src{idx}_{len(clips)}.jpg"))
                    out = os.path.join(tmp, f"e{idx}_{len(clips)}.mp4")
                    clip_imagen(src, sub, out); os.remove(src)
                    clips.append(out); usados.add(h["id"]); creditos.add(f"{h['user']} (Pixabay)")
            else:
                for h in commons(q, clave, usados)[:partes - len(clips)]:
                    src = bajar(h["url"], os.path.join(tmp, f"src{idx}_{len(clips)}.img"))
                    out = os.path.join(tmp, f"e{idx}_{len(clips)}.mp4")
                    clip_imagen(src, sub, out, completo=True); os.remove(src)
                    clips.append(out); usados.add(h["id"]); creditos.add(h["credito"])
        except Exception as ex:
            print("aviso", tipo, q, ex, file=sys.stderr)
        if len(clips) >= partes:
            break
    if clips and len(clips) < partes:  # un solo clip relevante: se estira a toda la escena
        out = os.path.join(tmp, f"e{idx}_full.mp4")
        ff("-stream_loop", "-1", "-i", clips[0], "-t", f"{seg:.3f}", "-c", "copy", out)
        clips = [out]
    return clips


def crear_marca(c, tmp):
    """Marca de agua: logo redondo + nombre del canal sobre una píldora oscura (arriba a la izquierda)."""
